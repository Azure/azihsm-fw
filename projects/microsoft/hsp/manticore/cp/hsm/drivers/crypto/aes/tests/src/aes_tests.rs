fn enable_rng() {
    let rng_regs = RngRegs::block();
    rng_regs.ctrl().read_and_modify(|_, w| w.enable(true));
    mcr_cpu::cpu_stall(RNG_INIT_DELAY);
}

fn test_aes(
    mode: AesMode,
    op: AesOp,
    message: &[u8],
    key: &[u8],
    iv: Option<&[u8]>,
    expected: &[u8],
) {
    let message_buf = create_message_buff(message.len());
    message_buf[..message.len()].copy_from_slice(message);

    let key_buf = create_key_buff(key.len());
    key_buf[..key.len()].copy_from_slice(key);

    let iv_buf = if let Some(iv) = iv {
        let iv_buf = create_iv_buff(iv.len());
        iv_buf[..iv.len()].copy_from_slice(iv);
        Some(MborByteArray::<16>::new_with_len(
            iv_buf.as_ptr(),
            iv_buf.len(),
        ))
    } else {
        None
    };

    let result_buf = create_result_buff(expected.len());

    let tag = 0xFE;

    let message_mbor: MborByteArray<1024> =
        MborByteArray::new_with_len(message_buf.as_ptr(), message_buf.len());
    let message_binding = (&message_mbor).into();

    let result_mbor: MborByteArray<1024> =
        MborByteArray::new_with_len(result_buf.as_ptr(), result_buf.len());
    let result_binding = (&result_mbor).into();

    enable_rng();

    let aes = Aes::new(create_aes_cmd_buff());

    if let Some(iv) = iv_buf {
        let iv_binding = (&iv).into();
        let cmd_info = AesCommand {
            tag,
            message: &message_binding,
            iv: Some(&iv_binding),
            key: key_buf,
            mode,
            op,
            update_iv: false,
            result: &result_binding,
        };

        let status = aes.encrypt_decrypt(&cmd_info);
        assert_eq!(status, Ok(()));
    } else {
        let cmd_info = AesCommand {
            tag,
            message: &message_binding,
            iv: None,
            key: key_buf,
            mode,
            op,
            update_iv: false,
            result: &result_binding,
        };

        let status = aes.encrypt_decrypt(&cmd_info);
        assert_eq!(status, Ok(()));
    }

    assert_eq!(result_buf, expected);
}

fn test_aes_interrupt(
    mode: AesMode,
    op: AesOp,
    message: &[u8],
    key: &[u8],
    iv: Option<&[u8]>,
    expected: &[u8],
) {
    let message_buf = create_message_buff(message.len());
    message_buf[..message.len()].copy_from_slice(message);

    let key_buf = create_key_buff(key.len());
    key_buf[..key.len()].copy_from_slice(key);

    let iv_buf = if let Some(iv) = iv {
        let iv_buf = create_iv_buff(iv.len());
        iv_buf[..iv.len()].copy_from_slice(iv);
        Some(MborByteArray::<16>::new_with_len(
            iv_buf.as_ptr(),
            iv_buf.len(),
        ))
    } else {
        None
    };

    let result_buf = create_result_buff(expected.len());
    let tag = 0xFE;
    let intc = InterruptController::default();

    let message_mbor: MborByteArray<1024> =
        MborByteArray::new_with_len(message_buf.as_ptr(), message_buf.len());
    let message_binding = (&message_mbor).into();

    let result_mbor: MborByteArray<1024> =
        MborByteArray::new_with_len(result_buf.as_ptr(), result_buf.len());
    let result_binding = (&result_mbor).into();

    enable_rng();

    let aes = Aes::new(create_aes_cmd_buff());

    intc.clear(Interrupt::aes_done_irq);
    intc.clear(Interrupt::aes_error_irq);

    if let Some(iv) = iv_buf {
        let iv_binding = (&iv).into();
        let cmd_info = AesCommand {
            tag,
            message: &message_binding,
            iv: Some(&iv_binding),
            key: key_buf,
            mode,
            op,
            update_iv: false,
            result: &result_binding,
        };

        let status = aes.encrypt_decrypt(&cmd_info);
        assert_eq!(status, Ok(()));
    } else {
        let cmd_info = AesCommand {
            tag,
            message: &message_binding,
            iv: None,
            key: key_buf,
            mode,
            op,
            update_iv: false,
            result: &result_binding,
        };

        let status = aes.encrypt_decrypt(&cmd_info);
        assert_eq!(status, Ok(()));
    }

    if intc.pending(Interrupt::aes_done_irq) {
        intc.clear(Interrupt::aes_done_irq);
    }
    assert_eq!(intc.pending(Interrupt::aes_error_irq), false);

    assert_eq!(result_buf, expected);
}

