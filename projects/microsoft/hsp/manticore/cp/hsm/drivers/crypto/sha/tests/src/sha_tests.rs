pub const SHA_CMD_BUFF: u32 = 0x61151000;
pub const SHA_DIGEST_BUFF: u32 = 0x61151400;
pub const SHA_INPUT_BUFF: u32 = 0x61151800;
pub const SHA_INIT_DIGEST_BUFF: u32 = 0x61151C00;
pub const SHA_LARGE_INPUT_BUFF: u32 = 0x61152000;
pub const SELF_TEST_BUFF: u32 = 0x61154000;

const PRK_DATA_LEN: usize = SHA_MAX_BLOCK_SIZE;
const SHA_HW_UNIT_TEST_BUFF_SIZE: usize = 1024;

pub fn create_sha_cmd_buff() -> &'static mut ShaCommandDesc {
    let ptr: *mut ShaCommandDesc = SHA_CMD_BUFF as *mut ShaCommandDesc;
    let reg: &mut ShaCommandDesc = unsafe { core::mem::transmute(ptr) };

    reg
}

pub fn create_digest_buff(len: usize) -> &'static [u8] {
    unsafe { core::slice::from_raw_parts(SHA_DIGEST_BUFF as *const u8, len) }
}

pub fn create_test_buf(addr: u32, len: usize) -> &'static mut [u8] {
    unsafe { core::slice::from_raw_parts_mut(addr as *mut u8, len) }
}

pub fn create_init_digest_buff(len: usize) -> &'static mut [u8] {
    unsafe { core::slice::from_raw_parts_mut(SHA_INIT_DIGEST_BUFF as *mut u8, len) }
}

pub fn create_input_buff(len: usize) -> &'static mut [u8] {
    unsafe { core::slice::from_raw_parts_mut(SHA_INPUT_BUFF as *mut u8, len) }
}

pub fn create_large64k_buff(len: usize) -> &'static mut [u8] {
    unsafe { core::slice::from_raw_parts_mut(SHA_LARGE_INPUT_BUFF as *mut u8, len) }
}

fn get_digest_size(mode: ShaMode) -> usize {
    match mode {
        ShaMode::Sha1 => 20,
        ShaMode::Sha256 => 32,
        ShaMode::Sha384 => 48,
        ShaMode::Sha512 => 64,
    }
}

fn get_digest_size_hw(mode: ShaMode) -> usize {
    match mode {
        ShaMode::Sha1 => 20,
        ShaMode::Sha256 => 32,
        // HS SHA requires the initial digest for SHA-384 to be 64 bytes.
        ShaMode::Sha384 => 64,
        ShaMode::Sha512 => 64,
    }
}

fn init_sha() -> Sha {
    Sha::new(
        create_sha_cmd_buff(),
        create_init_digest_buff(SHA_DIGEST_MAX_SIZE_BYTES),
        create_test_buf(SELF_TEST_BUFF, SHA_HW_UNIT_TEST_BUFF_SIZE),
    )
}

fn test_digest_helper(input: &str, expected: &[u8], sha_mode: ShaMode) {
    let input_data = create_input_buff(input.len());
    input_data[..input.len()].copy_from_slice(input.as_bytes());
    let input_range = IoMemRange::from(input_data);

    let output = create_digest_buff(SHA_DIGEST_MAX_SIZE_BYTES);
    let mut output_range = IoMemRange::from(output);

    let cmd_info = ShaDigestCmdInfoZc {
        buffer: &input_range,
        init_digest: None,
        mode: sha_mode,
        last: true,
        len: input.len() as u32,
        total_len: input.len() as u32,
        output_buffer: &mut output_range,
    };

    let sha = init_sha();

    let _result = sha.digest_zc(&cmd_info).unwrap();

    assert_eq!(&output[..get_digest_size(sha_mode)], expected);
}

