fn kbkdf_compute_helper(kbkdf_info: KbkdfInfo, sha_mode: ShaMode, expected_key_output: &[u8]) {
    // n := ceil(L/h)
    // KDF_OUT_BUF_SIZE = n * digest_size
    // const N: usize = (L_BYTES + SHA_DIGEST_MAX_SIZE_BYTES - 1) / SHA_DIGEST_MAX_SIZE_BYTES;
    const KDF_OUT_BUF_SIZE: usize = 2 * SHA_MAX_BLOCK_SIZE;
    // Data size for Aes256 key type, the max key size for AES keys
    const KEY_DATA_LEN: usize = 64;

    let sha = init_sha();

    // Split the self_test_buf into key buffer + output buffer + input buffer
    // key buffer = self_test_buf[..KEY_DATA_LEN]
    // output buffer = self_test_buf[KEY_DATA_LEN..KEY_DATA_LEN + KDF_OUT_BUF_SIZE]
    // input buffer = self_test_buf[KEY_DATA_LEN + KDF_OUT_BUF_SIZE..]
    let self_test_buf = create_test_buf(SELF_TEST_BUFF, SHA_HW_UNIT_TEST_BUFF_SIZE);
    let _key_mborbytearray = MborByteArray::<KEY_DATA_LEN>::new_with_len(
        self_test_buf[..KEY_DATA_LEN].as_ptr(),
        KEY_DATA_LEN,
    );

    let self_test_buf = create_test_buf(SELF_TEST_BUFF, SHA_HW_UNIT_TEST_BUFF_SIZE);
    let input_mborbytearray = MborByteArray::<SHA_HW_UNIT_TEST_BUFF_SIZE>::new_with_len(
        self_test_buf[KEY_DATA_LEN + KDF_OUT_BUF_SIZE..].as_ptr(),
        self_test_buf.len() - KEY_DATA_LEN - KDF_OUT_BUF_SIZE,
    );

    let self_test_buf = create_test_buf(SELF_TEST_BUFF, SHA_HW_UNIT_TEST_BUFF_SIZE);
    let output_buf = &mut self_test_buf[KEY_DATA_LEN..KEY_DATA_LEN + KDF_OUT_BUF_SIZE];

    sha.kbkdf_counter_hmac(
        kbkdf_info,
        sha_mode,
        &mut (&input_mborbytearray).into(),
        output_buf,
    )
    .unwrap();

    // Ensure that the output matches the expected known output vector
    assert_eq!(
        &output_buf[..expected_key_output.len()],
        expected_key_output
    );
}

