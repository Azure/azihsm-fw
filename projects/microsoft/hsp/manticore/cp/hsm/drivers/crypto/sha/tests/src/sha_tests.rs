// Test vectors from: https://datatracker.ietf.org/doc/html/rfc4231#section-4.2
fn hmac_compute_helper(key: &[u8], data: &[u8], sha_mode: ShaMode, expected_hmac: &[u8]) {
    // All keys larger than the hw block size will be hashed down to hash digest size.
    // Since the largest hw block size is 128, the buffer is created to test with keys longer than 128.
    const MAX_KEY_LEN: usize = 256;

    let key_buf = create_input_buff(MAX_KEY_LEN);

    let sha = init_sha();

    let sha_digest_size_hw = get_digest_size_hw(sha_mode);
    // Separate the allocated buf to input and output buffer
    let self_test_buf = create_test_buf(SELF_TEST_BUFF, SHA_HW_UNIT_TEST_BUFF_SIZE);
    let digest_mborbytearray = MborByteArray::<SHA_HW_UNIT_TEST_BUFF_SIZE>::new_with_len(
        self_test_buf.as_ref().as_ptr(),
        sha_digest_size_hw,
    );
    let output_buffer = &mut IoMemRange::from(&digest_mborbytearray);

    let self_test_buf = create_test_buf(SELF_TEST_BUFF, SHA_HW_UNIT_TEST_BUFF_SIZE);
    let input_mborbytearray = MborByteArray::<SHA_HW_UNIT_TEST_BUFF_SIZE>::new_with_len(
        self_test_buf.as_ref()[sha_digest_size_hw..].as_ptr(),
        self_test_buf.len() - sha_digest_size_hw,
    );
    let input_buffer = &mut IoMemRange::from(&input_mborbytearray);

    // Key needs to be in GSRAM to be processed
    key_buf[..key.len()].copy_from_slice(key);

    sha.hmac(
        &key_buf[..key.len()],
        data,
        sha_mode,
        input_buffer,
        output_buffer,
    )
    .unwrap();

    assert_eq!(&output_buffer.slice()[..expected_hmac.len()], expected_hmac);
}

fn test_hkdf_large_out_len_err() {
    const KDF_OUT_BUF_SIZE: usize = 2 * SHA_MAX_BLOCK_SIZE;

    let sha = init_sha();

    // Split the self_test_buf into key buffer + output buffer + input buffer
    // key buffer = self_test_buf[..PRK_DATA_LEN]
    // output buffer = self_test_buf[PRK_DATA_LEN..PRK_DATA_LEN + KDF_OUT_BUF_SIZE]
    // input buffer = self_test_buf[PRK_DATA_LEN + KDF_OUT_BUF_SIZE..]
    let self_test_buf = create_test_buf(SELF_TEST_BUFF, SHA_HW_UNIT_TEST_BUFF_SIZE);
    let key_mborbytearray = MborByteArray::<PRK_DATA_LEN>::new_with_len(
        self_test_buf[..PRK_DATA_LEN].as_ptr(),
        PRK_DATA_LEN,
    );

    let self_test_buf = create_test_buf(SELF_TEST_BUFF, SHA_HW_UNIT_TEST_BUFF_SIZE);
    let input_mborbytearray = MborByteArray::<SHA_HW_UNIT_TEST_BUFF_SIZE>::new_with_len(
        self_test_buf[PRK_DATA_LEN + KDF_OUT_BUF_SIZE..].as_ptr(),
        self_test_buf.len() - PRK_DATA_LEN - KDF_OUT_BUF_SIZE,
    );

    let self_test_buf = create_test_buf(SELF_TEST_BUFF, SHA_HW_UNIT_TEST_BUFF_SIZE);
    let output_buf = &mut self_test_buf[PRK_DATA_LEN..PRK_DATA_LEN + KDF_OUT_BUF_SIZE];

    let sha_mode = ShaMode::Sha256;

    // out_len set to exceed max value of 68
    let hkdf_info = HkdfInfo {
        key: &[0u8; 1],
        salt: &[0u8; 1],
        info: &[0u8; 1],
        out_len: 69,
    };

    let result = sha.hkdf(
        hkdf_info,
        sha_mode,
        &mut (&key_mborbytearray).into(),
        &mut (&input_mborbytearray).into(),
        output_buf,
    );
    assert_eq!(result.unwrap_err(), 0x7000B);
}

