#[test]
fn test_alias_cert_decoder() {
    let cert_der = TEST_CERTIFICATE;

    let cert1 = X509::from_der(&cert_der).expect("Failed to parse certificate");
    println!("{:?}", cert1);

    let common_name = get_subject_cn(&cert_der).expect("Failed to get subject common name");
    println!("Subject Common Name: {:?}", common_name);

    let subject_key_id =
        get_subject_key_identifier(&cert_der).expect("Failed to get subject key ID");
    println!("Subject Key ID: {:?}", subject_key_id);

    // Compare the extracted common name with the actual common name from the certificate
    let actual_cn = cert1
        .subject_name()
        .entries_by_nid(Nid::COMMONNAME)
        .next()
        .expect("Failed to extract common name from X509 subject")
        .data()
        .as_slice();

    assert_eq!(actual_cn, common_name);

    let actual_subject_key_id = cert1
        .subject_key_id()
        .expect("Failed to get subject key ID from X509 certificate")
        .as_slice();
    assert_eq!(actual_subject_key_id, subject_key_id);
}
