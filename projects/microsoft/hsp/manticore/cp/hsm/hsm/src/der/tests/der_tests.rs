fn test_asn1_rsa_key_decode(size: u32) {
    let exp: BigNum = BigNum::from_u32(0x10001).unwrap();

    let rsa_private_openssl = openssl::rsa::Rsa::generate_with_e(size, &exp).unwrap();
    let pkey = openssl::pkey::PKey::from_rsa(rsa_private_openssl).unwrap();

    // Generate the DER from openssl generated key.
    let rsa_private_der_openssl = pkey.private_key_to_pkcs8().unwrap();

    // Get the raw openssl key data.
    let modulus_openssl = pkey.rsa().unwrap().n().to_owned().unwrap().to_vec();
    let public_exponent_openssl = pkey.rsa().unwrap().e().to_owned().unwrap().to_vec();
    let private_exponent_openssl = pkey.rsa().unwrap().d().to_owned().unwrap().to_vec();
    let prime1_openssl = pkey.rsa().unwrap().p().to_owned().unwrap().to_vec();
    let prime2_openssl = pkey.rsa().unwrap().q().to_owned().unwrap().to_vec();
    let exponent1_openssl = pkey.rsa().unwrap().dmp1().to_owned().unwrap().to_vec();
    let exponent2_openssl = pkey.rsa().unwrap().dmq1().to_owned().unwrap().to_vec();
    let coefficient_openssl = pkey.rsa().unwrap().iqmp().to_owned().unwrap().to_vec();

    // Convert the openssl DER to raw using HSM DER encoder.
    let raw_key_data = rsa_private_der_openssl.as_slice().rsa_der_to_raw().unwrap();

    assert!(raw_key_data.modulus == modulus_openssl.into());
    assert!(raw_key_data.public_exponent == public_exponent_openssl.into());
    assert!(raw_key_data.private_exponent == private_exponent_openssl.into());
    assert!(raw_key_data.exponent1 == exponent1_openssl.into());
    assert!(raw_key_data.exponent2 == exponent2_openssl.into());
    assert!(raw_key_data.prime1 == prime1_openssl.into());
    assert!(raw_key_data.prime2 == prime2_openssl.into());
    assert!(raw_key_data.coefficient == coefficient_openssl.into());

    let rsa_type = raw_key_data.priv_key().rsa_type;
    let priv_key_pka = raw_key_data.priv_key().to_pka_bytes().unwrap();

    assert_eq!(priv_key_pka.len(), 2 * rsa_type.len() + 4);
}

