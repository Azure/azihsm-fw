pub(crate) fn generate_ecc_openssl(curve: EccCurve) -> Result<(PKey<Private>, PKey<Public>), ()> {
    let curve_name = match curve {
        EccCurve::P256 => Nid::X9_62_PRIME256V1,
        EccCurve::P384 => Nid::SECP384R1,
        EccCurve::P521 => Nid::SECP521R1,
    };
    let group = openssl::ec::EcGroup::from_curve_name(curve_name).map_err(|_| ())?;
    let ecc_private = openssl::ec::EcKey::generate(&group).map_err(|_| ())?;
    let ecc_public =
        openssl::ec::EcKey::from_public_key(&group, ecc_private.public_key()).map_err(|_| ())?;

    let pkey_private = openssl::pkey::PKey::from_ec_key(ecc_private).map_err(|_| ())?;
    let pkey_public = openssl::pkey::PKey::from_ec_key(ecc_public).map_err(|_| ())?;

    Ok((pkey_private, pkey_public))
}

fn coordinates_from_pubkey(pubkey: PKey<Public>) -> Result<(Vec<u8>, Vec<u8>), ()> {
    let ec_key = pubkey.ec_key().map_err(|_| ())?;
    let group = ec_key.group();
    let mut x = BigNum::new().map_err(|_| ())?;
    let mut y = BigNum::new().map_err(|_| ())?;
    let mut ctx = BigNumContext::new().map_err(|_| ())?;

    ec_key
        .public_key()
        .affine_coordinates(group, &mut x, &mut y, &mut ctx)
        .map_err(|_| ())?;

    Ok((x.to_vec(), y.to_vec()))
}

fn test_asn1_ecc_key256_decode() {
    let curve = EccCurve::P256;

    // Generate ECC public key/private key using openssl.
    let (pkey_private, pkey_public) = generate_ecc_openssl(curve).unwrap();
    let (x_openssl, y_openssl) = coordinates_from_pubkey(pkey_public.clone()).unwrap();

    // Convert the ECC private key to DER format using openssl.
    let priv_key_der_openssl = pkey_private.private_key_to_pkcs8().unwrap();

    // Get the raw private key using OpenSSL.
    let priv_key_raw_openssl = pkey_private.ec_key().unwrap().private_key().to_vec();

    // Get the raw public and private keys using HSM DER decoder.
    let ecc_key_data = priv_key_der_openssl
        .as_slice()
        .ecc_priv_key_pkcs8_der_to_raw()
        .unwrap();

    assert!(ecc_key_data.orig_priv_key == SecureByteVec::from(priv_key_raw_openssl));
    assert!(ecc_key_data.orig_pub_key_x == x_openssl);
    assert!(ecc_key_data.orig_pub_key_y == y_openssl);

    let pka_curve: PkaEccCurve = curve.into();
    let ecc_priv_key_pka = ecc_key_data.priv_key().unwrap().to_pka_bytes().unwrap();
    assert_eq!(ecc_priv_key_pka.len(), pka_curve.len());
}

fn test_ecc_decode_non_rounded_size_helper(curve: EccCurve, priv_key_der_openssl: &[u8]) {
    let pkey_priv_key_openssl =
        openssl::pkey::PKey::private_key_from_pkcs8(priv_key_der_openssl).unwrap();

    let group = openssl::ec::EcGroup::from_curve_name(curve.into())
        .map_err(|_| ())
        .unwrap();

    let pkey_pubkey_openssl = openssl::ec::EcKey::from_public_key(
        &group,
        pkey_priv_key_openssl.ec_key().unwrap().public_key(),
    )
    .map_err(|_| ())
    .unwrap();

    let (x_openssl, y_openssl) = {
        let group = pkey_pubkey_openssl.group();
        let mut x = BigNum::new().map_err(|_| ()).unwrap();
        let mut y = BigNum::new().map_err(|_| ()).unwrap();
        let mut ctx = BigNumContext::new().map_err(|_| ()).unwrap();

        pkey_pubkey_openssl
            .public_key()
            .affine_coordinates(group, &mut x, &mut y, &mut ctx)
            .map_err(|_| ())
            .unwrap();

        (x.to_vec(), y.to_vec())
    };

    let priv_key_raw_openssl = pkey_priv_key_openssl
        .ec_key()
        .unwrap()
        .private_key()
        .to_vec();

    // Get the raw public and private keys using HSM DER decoder.
    let ecc_key_data = priv_key_der_openssl
        .ecc_priv_key_pkcs8_der_to_raw()
        .unwrap();

    assert!(ecc_key_data.orig_priv_key == SecureByteVec::from(priv_key_raw_openssl));
    assert!(ecc_key_data.orig_pub_key_x == x_openssl);
    assert!(ecc_key_data.orig_pub_key_y == y_openssl);

    let pka_curve: PkaEccCurve = curve.into();
    let ecc_priv_key_pka = ecc_key_data.priv_key().unwrap().to_pka_bytes().unwrap();
    assert_eq!(ecc_priv_key_pka.len(), pka_curve.len());
}

