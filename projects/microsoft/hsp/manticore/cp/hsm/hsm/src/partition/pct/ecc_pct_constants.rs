/// Stores precomputed ECC test key pairs (static values for testing and validation)
pub struct EcdhTestKeyPairs {
    pub key_pairs: [PkaEccKeyPair; 3],
}

/// Implementation for looking up keys
impl EcdhTestKeyPairs {
    /// Get the private key for a given curve (Used in ECDH)
    pub fn get_private_key(&self, curve: PkaEccCurve) -> Option<&PkaEccPrivateKey> {
        self.key_pairs
            .iter()
            .find(|kp| kp.priv_key.curve == curve)
            .map(|kp| &kp.priv_key)
    }

    /// Get the public key for a given curve
    pub fn get_public_key(&self, curve: PkaEccCurve) -> Option<&PkaEccPublicKey> {
        self.key_pairs
            .iter()
            .find(|kp| kp.pub_key.curve == curve)
            .map(|kp| &kp.pub_key)
    }
}

