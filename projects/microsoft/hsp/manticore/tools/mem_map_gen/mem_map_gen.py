from textwrap import dedent
from collections import defaultdict
import argparse
import csv
import re
from bs4 import BeautifulSoup


def create_h_file (mem_map_dict, out_dir, map_name):
    """
    Creates header file from the mem map dictionary

    :param mem_map_dict (dict): Dictionary with module names, their offset, size, and type.
    :param out_dir (str): Output directory for the CSV file.
    :param map_name (str): Name of the mem map .

    :return: None
    """
    filtered_mem_map = {}

    # Filtering dictionary items by required attributes
    for name, attributes in mem_map_dict.items ():
        if set ( ('offset','size','type')).issubset (attributes.keys ()):
            filtered_mem_map[name]=attributes

    # Sorting the dict based on value : 'offset'
    sorted_mem_map = dict(sorted(filtered_mem_map.items(),
                                 key=lambda item: int(item[1]['offset'], 16)))
    map_name = map_name.upper() + "_MEM_MAP"

    header_content = dedent(f"""\
        // Copyright (c) Microsoft Corporation. All rights reserved.
        // This is an autogenerated file using mem_map_gen.py. Do not edit manually.

        #ifndef {map_name}_H_
        #define {map_name}_H_

        enum {{""")

    for name, attributes in sorted_mem_map.items ():
        header_content += (f"\n\t{map_name.upper()}_{name.upper()} = {attributes['offset']},")
        header_content += (f"\n\t{map_name.upper()}_{name.upper()}_SIZE = {attributes['size']},")

    header_content += dedent(f"""
        }};

        #endif	//	{map_name}_H_
    """)

    with open(f'{out_dir}/{map_name.lower()}.h', "w", encoding="utf-8") as hfile:
        hfile.write(header_content)

def create_csv (mem_map_dict, out_dir, map_name):
    """
    Writes the final dictionary to a CSV file.

    :param mem_map_dict (dict): Dictionary with module names, their offset, size, and type.
    :param out_dir (str): Output directory for the CSV file.
    :param map_name (str): Name of the mem map .

    :return: None
    """
    filtered_mem_map = {}

    # Filtering dictionary items by required attributes
    for name, attributes in mem_map_dict.items ():
        if set ( ('offset','size','type')).issubset (attributes.keys ()):
            filtered_mem_map[name]=attributes

    # Sorting the dict based on value : 'offset'
    sorted_mem_map = dict(sorted(filtered_mem_map.items(),
                                 key=lambda item: int(item[1]['offset'], 16)))

    with open (f'{out_dir}/{map_name}_mem_map.csv', mode='w',
               newline='', encoding='utf-8') as csv_file:

        csv_file.write("# This is an auto-generated file. Do not edit manually.\n")
        writer = csv.writer (csv_file)
        writer.writerow (['field', 'address', 'size', 'type'])

        # Write the data rows
        for name, attributes in sorted_mem_map.items ():
            writer.writerow ([name.lower(),
                            attributes['offset'],
                            attributes['size'],
                            attributes['type']])

def extract_offset_size (soup):
    """
    Extracts offset and size values from the HTML content and returns a dictionary.

    :param soup (BeautifulSoup): Parsed BeautifulSoup object.

    :return (dict): Dictionary with module names as keys and their offset and size as values.
    """
    # Create an empty dictionary with default dict
    mem_map_dict = defaultdict (dict)

    # Find the <ul> element with class 'block associatedconstant'
    ul_element = soup.find ('ul', class_='block associatedconstant')

    # Extract all <li> elements within this <ul>
    list_items = ul_element.find_all ('li') if ul_element else []

    for li in list_items:
        # Extract the <a> element within the <li>
        anchor_tag = li.find ('a')
        if anchor_tag:
            # Extract the href attribute
            href = anchor_tag.get ('href')
            if href:
                # Find the referenced content in the same HTML file
                referenced_content = soup.find (id=href.lstrip ('#'))
                if referenced_content:
                    name = li.text
                    if name.endswith ("_OFFSET"):
                        name = name[:-(len("_OFFSET"))]
                        # Extracting out the numerical value post '='
                        mem_map_dict[name]['offset'] = hex (int (re.findall (r'=\s*(.*)usize',
                                                   referenced_content.text)[0]))
                    elif name.endswith ("_SIZE"):
                        name = name[:-(len("_SIZE"))]
                        # Extracting out the numerical value post '='
                        mem_map_dict[name]['size'] = hex (int (re.findall (r'=\s*(.*)usize',
                                                   referenced_content.text)[0]))

    return mem_map_dict

def extract_type (soup, mem_map_dict):
    """
    Extracts type values and adds them to the parameter dictionary.

    :param soup (BeautifulSoup): Parsed BeautifulSoup object.
    :param mem_map_dict (dict): Dictionary with module names and their offset and size.

    :return (dict): Updated dictionary with type values added.
    """
    for name in mem_map_dict.keys ():

        method_id= 'method.'+ name.lower ()
        referenced_content = soup.find (id= method_id)

        if referenced_content:
            # Extract the string after the string 'static' which is the type
            data_type= re.findall (r'.*?static\s*(.*)', referenced_content.text, flags=re.DOTALL)[0]
            mem_map_dict[name]['type'] = re.sub (r'\s+', ' ', data_type).strip ()

    return mem_map_dict

if __name__ == '__main__':

#   This script generates the csv and c header files which contains offset and size of the memory
#   map components.
#
#   Args: -f [path of the html file containing MemMap documentation generated from cargo doc]
#         -oh <output directory for .h files>
#         -oc <output directory for .csv files>
#
#   If output path is not specified script will consider current directory.

    parser = argparse.ArgumentParser ()
    parser.add_argument ('-f', '--html_files', nargs='+', required=True, help='Input html files '
                                                                          'containing Mem Map '
                                                                          'documentation')
    parser.add_argument('-oh', '--output_h', default='.', help='Output directory for .h files')
    parser.add_argument('-oc', '--output_csv', default='.', help='Output directory for .csv files')
    args = parser.parse_args ()

    input_files = args.html_files
    out_dir_h = args.output_h
    out_dir_csv = args.output_csv

    for file in input_files :
        # Read the HTML files
        with open (file, 'r', encoding='utf-8') as file:
            html_content = file.read ()

        # Parse the HTML content using the built-in html.parser
        html_soup = BeautifulSoup (html_content, 'html.parser')
        mem_map_ram = extract_offset_size(html_soup)
        mem_map_ram = extract_type(html_soup,mem_map_ram)

        # Extracting out the Mem Map identifier
        mem_map_name = re.search(r"struct\.(.*?)MemMap\.html", str(file)).group(1)
        create_csv(mem_map_ram ,out_dir_csv,mem_map_name)
        create_h_file(mem_map_ram ,out_dir_h,mem_map_name)
