def read_file_data (path):
    """
    Read all the data from a file.

    :param path: The path to the file to read.

    :return The file contents.
    """

    file_read = open (path, "rb")
    data = file_read.read ()
    file_read.close ()

    return data

def write_file_data (path, *args):
    """
    Write a complete set of data to a file.

    :param path: The path of the file to write.
    :param args: A list of data buffers that will be sequentially written to the file.
    """

    file_write = open (path, "wb")
    for arg in args:
        file_write.write (arg)
    file_write.close ()

def prepare_signing_directory (path):
    """
    Prepare the working directories for signing operations.

    :param path: The path to initialize for signing.
    """

    if (not os.path.exists (path)):
        os.makedirs (path)
    else:
        for name in os.listdir (path):
            os.unlink (os.path.join (path, name))

def read_4byte_word (img, offset):
    """
    Read a 4-byte word from the image data.

    :param img: A binary array containing the firmware image.
    :param offset: The offset where the word should be read from.

    :return The data.
    """

    return img[offset] | (img[offset + 1] << 8) | (img[offset + 2] << 16) | (img[offset + 3] << 24)

def read_2byte_word (img, offset):
    """
    Read a 2-byte word from the image data.

    :param img: A binary array containing the image.
    :param offset: The offset where word should be read from.

    :return The data.
    """

    return img[offset] | (img[offset + 1] << 8)

def write_4byte_word (img, offset, data):
    """
    Write a 4-byte word to the image data.

    :param img: A binary array containing the firmware image.
    :param offset: The offset where the word should be written.
    :param data: The data to write.
    """

    img[offset:offset + 4] = struct.pack ("<I", data)

def write_2byte_word (img, offset, data):
    """
    Write a 2-byte word to the image data.

    :param img: A binary array containing the firmware image.
    :param offset: The offset where the word should be written.
    :param data: The data to write.
    """

    img[offset:offset + 2] = struct.pack ("<H", data)

def parse_boot_image (img):
    """
    Get the length of the 1SP boot image.

    :param img: A binary array containing the firmware image.  The boot image is at offset 0.

    :return A tuple containing the transfer manifest, key manifest, and 1SP image lengths.
    """

    xfer_manifest = read_4byte_word (img, 0)
    if (xfer_manifest == 0x4e554c4c):
        # Null transfer manifest
        xfer_length = 4
    elif (xfer_manifest == 0x6f776e74):
        # Ownership transfer manifest
        xfer_length = 344
    elif (xfer_manifest == 0x746d616e):
        # Tenancy grand manifest
        xfer_length = 300
    else:
        print ("Unknown transfer manifest type: {:08x}".format (xfer_manifest))
        sys.exit (1)

    key_length = 448    # Owner and Tenant key manifests are the same length
    hdr_length = 284    # 1SP image header

    # Image data length it at byte offset 232 in the 1SP header
    img_length = read_4byte_word (img, xfer_length + key_length + 232)

    return xfer_length, key_length, hdr_length + img_length

def parse_firmware_component (img, start):
    """
    Get the length of a firmware component.

    :param img: A binary array containing the complete firmware image.
    :param start: The offset within the array where the firmware component starts.

    :return A tuple with the length of the firmware component and the signature length.
    """

    hdr_length = read_2byte_word (img, start)
    img_length = read_4byte_word (img, start + 8)
    sig_length = read_2byte_word (img, start + 12)

    return hdr_length + img_length, sig_length

def parse_firmware_descriptor (img, start):
    """
    Get the length th firmware descriptor, including the firmware header.

    :param img: A binary array containing the complete firmware image.
    :param start: The offset within the array where the firmware header on the firmware descriptor
    starts.

    :return A tuple with the length of the firmware descriptor, the offset for the start of the
    descriptor, and the signature length.
    """

    hdr_length = read_2byte_word (img, start)
    img_length, sig_length = parse_firmware_component (img, start + hdr_length)

    return hdr_length + img_length, hdr_length, sig_length

def parse_build_version_number (img, version_offset):
    """
    Parse the build version number for the specified image.

    :param img: A binary array containing the complete firmware image.
    :param version_offset: The offset in the array that contains the build version to parse.

    :return A tuple with the base firmware version number in the form of major.minor.release.build,
    the firmware version extension (including build type), and the build type string.
    """

    build = img[version_offset]
    release = img[version_offset + 1]
    minor = img[version_offset + 2]
    major = img[version_offset + 3]
    version = "{0}.{1}.{2}.{3}".format (major, minor, release, build)

    type = img[version_offset + 4] & 0x1f
    build_time = read_4byte_word (img, version_offset + 4) >> 5
    version_ext = "{0}".format (build_time)

    if (type == 1):
        build_type = "rel"
    elif (type == 2):
        build_type = "dev"
    elif (type == 3):
        build_type = "beta"
    elif (type == 4):
        build_type = "evb"
    elif (type == 8):
        build_type = "rec"
    elif (type == 12):
        build_type = "test"
    elif (type == 0):
        build_type = ""
    else:
        print ("Unknown build version number extension type: {0}".format (type))
        sys.exit (1)

    return version, version_ext + build_type, build_type

def update_build_version (img, version_offset):
    """
    Update the build version number in a single header to indicate that the image is a production
    release.

    :param img: A binary array containing the firmware image.
    :param version_offset: Offset in the array to the build version entry that should be updated.

    :return A tuple wit the base firmware version and the version extension.
    """

    # Only need to modify a single byte at offset 4 in the 8-byte version number.
    version_offset += 4

    # Bits [4:0] represent the build type.  This is further divided between bits [4:2] and [1:0] to
    # represent build configuration and type, respectively.  A prod build is defined as 0, so just
    # clear bits [1:0], maintaining the provided build configuration in the signed image.
    build_version = img[version_offset] & ~0x3
    img[version_offset] = build_version

    version, version_ext, _ = parse_build_version_number (img, version_offset - 4)
    return version, version_ext

def build_ecdsa_p384_der_signature (sig_file, pad_length = 0):
    """
    Read a raw ECDSA P-384 signature from a file and DER encode it.

    :param sig_file: The file containing the raw signature data.
    :param pad_length: Length to zero pad the resulting signature data.

    :return A binary array containing the DER encoded signature.
    """

    raw_sig = read_file_data (sig_file)

    sig_r = raw_sig[0:48]
    sig_s = raw_sig[48:96]

    # Strip leading zeros from r and s values.
    while (sig_r[0] == 0):
        del sig_r[0]

    while (sig_s[0] == 0):
        del sig_s[0]

    # DER sequence
    der_sig = bytearray ([0x30])
    der_sig.append (0)

    # Encode r as an INTEGER, padding with a 0 as necessary.
    der_sig.append (0x02)
    if ((sig_r[0] & 0x80) != 0):
        der_sig.append (len (sig_r) + 1)
        der_sig.append (0)
    else:
        der_sig.append (len (sig_r))
    der_sig.extend (sig_r)

    # Encode s as an INTEGER, padding with a 0 as necessary.
    der_sig.append (0x02)
    if ((sig_s[0] & 0x80) != 0):
        der_sig.append (len (sig_s) + 1)
        der_sig.append (0)
    else:
        der_sig.append (len (sig_s))
    der_sig.extend (sig_s)

    # Set total length
    der_sig[1] = len (der_sig) - 2

    # Pad the array with zeros.
    while (len (der_sig) < pad_length):
        der_sig.append (0)

    return der_sig

def generate_image_checksum (img_file, img_version, checksum_file):
    """
    Generate a checksum file for a specific firmware image.

    :param img_file: The image file that should be hashed.
    :param img_version: The version string that should be reported in the file contents.
    :param checksum_file: The file that will contain the checksum data.
    """

    img_data = read_file_data (img_file)

    hdr = "Manticore FW v{0}\n".format (img_version).encode ('utf-8')
    sha256 = "SHA256: {0}\n".format (hashlib.sha256 (img_data).hexdigest ()).encode ('utf-8')
    sha384 = "SHA384: {0}\n".format (hashlib.sha384 (img_data).hexdigest ()).encode ('utf-8')
    sha512 = "SHA512: {0}\n".format (hashlib.sha512 (img_data).hexdigest ()).encode ('utf-8')

    write_file_data (checksum_file, hdr, sha256, sha384, sha512)

def generate_image_authorization (img_file, auth_token):
    """
    Generate an unsigned global authorization token for a specific firmware image.

    :param img_file: The image file to use for token generation.
    :param auth_token: The file that will contain the unsigned authorization data.
    """

    img_data = read_file_data (img_file)
    sha384 = hashlib.sha384 (img_data).digest ()

    # Create the authorization data
    auth_data = bytearray ([
        0x00,0x00,0x39,0x00,    # Header
        0x50,0x55,0x57,0x46,    # Marker
        0x00,0x00,0x00,0x00,    # Place-holder for the image length
        0x01                    # SHA-384
    ])

    auth_data.extend (sha384)
    write_4byte_word (auth_data, 8, len (img_data))

    write_file_data (auth_token, auth_data)
