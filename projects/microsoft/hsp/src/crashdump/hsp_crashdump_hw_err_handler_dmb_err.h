#ifndef HSP_CRASHDUMP_HW_ERR_HANDLER_DMB_ERR_H_
#define HSP_CRASHDUMP_HW_ERR_HANDLER_DMB_ERR_H_

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include "hsp_crashdump_hw_err_handler.h"
#include "hsp_top.h"
#include "mmio/mmio_register_block.h"
#include "status/msft_module_id.h"


/**
 * DMB error handler structure.
 */
struct hsp_crashdump_hw_err_handler_dmb_err {
	struct hsp_crashdump_hw_err_handler base;	/**< Base handler for a HSP HW error processing. */
	size_t creg_dmb_regs;						/**< DMB CREG offset referred for DMB error interrupt handling. */
	const struct mmio_register_block *dmb_regs;	/**< DMB registers referred for error logging. */
};


void hsp_crashdump_hw_err_handler_dmb_err_save_opaque_data (uint32_t *buffer, size_t length);
int hsp_crashdump_hw_err_handler_dmb_err_init (
	struct hsp_crashdump_hw_err_handler_dmb_err *handler,
	const struct hsp_crashdump_handler *crashdump_handler, const struct mmio_register_block *creg,
	size_t creg_dmb_regs, const struct mmio_register_block *dmb_regs);
void hsp_crashdump_hw_err_handler_dmb_err_release (
	const struct hsp_crashdump_hw_err_handler_dmb_err *handler);


#define	HSP_CRASHDUMP_HW_ERR_HANDLER_DMB_ERR_ERROR(code)      \
	ROT_ERROR (MSFT_MODULE_HSP_HANDLER_DMB_ERR, code)

/**
 * Error codes that can be generated by the DMB error handler.
 *
 * Note: Commented error codes have been deprecated.
 */
enum {
	HSP_CRASHDUMP_HW_ERR_HANDLER_DMB_ERR_INVALID_ARGUMENT =
		HSP_CRASHDUMP_HW_ERR_HANDLER_DMB_ERR_ERROR (0x00),	/**< Input parameter is null or not valid. */
	HSP_CRASHDUMP_HW_ERR_HANDLER_DMB_ERR_NO_MEMORY =
		HSP_CRASHDUMP_HW_ERR_HANDLER_DMB_ERR_ERROR (0x01),	/**< Memory allocation failed. */
	HSP_CRASHDUMP_HW_ERR_HANDLER_DMB_ERR_INT_STATUS_0 =
		HSP_CRASHDUMP_HW_ERR_HANDLER_DMB_ERR_ERROR (0x02),	/**< Interrupt status register value was 0. */
};


#endif	/* HSP_CRASHDUMP_HW_ERR_HANDLER_DMB_ERR_H_ */
