int hsp_aes_run_self_test_aes256_cbc (const struct hsp_aes *aes,
	const struct ccs_ksu_interface *ccs, uint8_t key_slot);


#define	HSP_AES_ERROR(code)		ROT_ERROR (MSFT_MODULE_HSP_AES, code)

/**
 * Error codes that can be generated by the HSP AES engine.
 */
enum {
	HSP_AES_INVALID_ARGUMENT = HSP_AES_ERROR (0x00),			/**< Input parameter is null or not valid. */
	HSP_AES_NO_MEMORY = HSP_AES_ERROR (0x01),					/**< Memory allocation failed. */
	HSP_AES_ENCRYPT_FAILED = HSP_AES_ERROR (0x02),				/**< Failed to encrypt data. */
	HSP_AES_DECRYPT_FAILED = HSP_AES_ERROR (0x03),				/**< Failed to decrypt data. */
	HSP_AES_INVALID_ADDRESS = HSP_AES_ERROR (0x04),				/**< A buffer is not in HSP shared SRAM. */
	HSP_AES_CMD_NOT_STARTED = HSP_AES_ERROR (0x05),				/**< The HS-SHA did not accept a submitted command. */
	HSP_AES_ADDRESS_NOT_ALIGNED = HSP_AES_ERROR (0x06),			/**< A buffer address is not word aligned. */
	HSP_AES_UNSUPPORTED_AES_MODE = HSP_AES_ERROR (0x07),		/**< The AES mode is not supported. */
	HSP_AES_OUTPUT_BUFFER_TOO_SMALL = HSP_AES_ERROR (0x08),		/**< The output buffer is not large enough for the data. */
	HSP_AES_NOT_BLOCK_ALIGNED = HSP_AES_ERROR (0x09),			/**< Data input is not aligned to the AES block size. */
	HSP_AES_UNSUPPORTED_KEY_SLOT = HSP_AES_ERROR (0x0a),		/**< The requested key slot is not available. */
	HSP_AES_SELF_TEST_FAILED = HSP_AES_ERROR (0x0b),			/**< A self-test of the AES HW failed. */
	HSP_AES_INPUT_BUFFER_TOO_LARGE = HSP_AES_ERROR (0x0c),		/**< The input buffer is too large to be handled. */
	HSP_AES_UNSUPPORTED_XTS_DATA_LENGTH = HSP_AES_ERROR (0x0d),	/**< The data unit length is not supported for AES-XTS. */
	HSP_AES_INVALID_XTS_DATA_LENGTH = HSP_AES_ERROR (0x0e),		/**< The data unit length is not valid for AES-XTS. */
	HSP_AES_CMD_EXE_TIMEOUT = HSP_AES_ERROR (0x0f),				/**< AES command execution timeout. */

	/* Error codes >0x80 are reserved for reporting bits from the HW status register. */
};

/**
 * An error has occurred with the hardware block.  The error code represents the status register
 * output.
 */
#define	HSP_AES_HW_ERROR(reg)	HSP_AES_ERROR (0x80 | ((reg & 0x38) >> 3))


#endif	/* HSP_AES_H_ */
